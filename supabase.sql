-- NHỊP CẦU YÊU THƯƠNG
-- Website công khai: người dùng chỉ xem + đăng ký tình nguyện.
-- Trang admin.html: chỉ tài khoản có role='admin' mới được thêm/sửa/xóa dữ liệu.

create extension if not exists "pgcrypto";

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.shelters (
  id bigint generated by default as identity primary key,
  name text not null,
  location text not null,
  category text not null check (category in ('food','medical','volunteer','supplies')),
  tag text,
  image text,
  description text not null,
  need text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.volunteers (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  name text not null,
  email text not null,
  help text not null,
  message text,
  created_at timestamptz not null default now()
);

create table if not exists public.site_settings (
  id integer primary key check (id=1),
  contact_email text not null default 'hello@example.com',
  updated_at timestamptz not null default now()
);
insert into public.site_settings(id,contact_email) values (1,'hello@example.com') on conflict (id) do nothing;

alter table public.profiles enable row level security;
alter table public.shelters enable row level security;
alter table public.volunteers enable row level security;
alter table public.site_settings enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path=public as $$
  select exists(select 1 from public.profiles where id=auth.uid() and role='admin');
$$;

-- PROFILE: admin page chỉ cần đọc role của chính mình.
drop policy if exists "profiles_select_own" on public.profiles;
create policy "profiles_select_own" on public.profiles for select to authenticated using (id=auth.uid() or public.is_admin());
drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles for insert to authenticated with check (id=auth.uid());

-- SHELTERS: ai cũng được xem, chỉ admin được thay đổi.
drop policy if exists "shelters_public_read" on public.shelters;
create policy "shelters_public_read" on public.shelters for select to anon,authenticated using (true);
drop policy if exists "shelters_admin_insert" on public.shelters;
create policy "shelters_admin_insert" on public.shelters for insert to authenticated with check (public.is_admin());
drop policy if exists "shelters_admin_update" on public.shelters;
create policy "shelters_admin_update" on public.shelters for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "shelters_admin_delete" on public.shelters;
create policy "shelters_admin_delete" on public.shelters for delete to authenticated using (public.is_admin());

-- VOLUNTEERS: người dùng không cần đăng nhập để gửi; chỉ admin được xem/xóa.
drop policy if exists "volunteers_public_insert" on public.volunteers;
create policy "volunteers_public_insert" on public.volunteers for insert to anon,authenticated with check (user_id is null or user_id=auth.uid());
drop policy if exists "volunteers_admin_read" on public.volunteers;
create policy "volunteers_admin_read" on public.volunteers for select to authenticated using (public.is_admin());
drop policy if exists "volunteers_admin_delete" on public.volunteers;
create policy "volunteers_admin_delete" on public.volunteers for delete to authenticated using (public.is_admin());

-- EMAIL LIÊN HỆ: ai cũng được đọc; chỉ admin được sửa.
drop policy if exists "settings_public_read" on public.site_settings;
create policy "settings_public_read" on public.site_settings for select to anon,authenticated using (true);
drop policy if exists "settings_admin_update" on public.site_settings;
create policy "settings_admin_update" on public.site_settings for update to authenticated using (public.is_admin()) with check (public.is_admin());
drop policy if exists "settings_admin_insert" on public.site_settings;
create policy "settings_admin_insert" on public.site_settings for insert to authenticated with check (public.is_admin());

