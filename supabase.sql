-- Cho trang công khai lấy tổng số lượt đăng ký mà không đọc dữ liệu cá nhân.
create or replace function public.get_public_volunteer_count()
returns bigint language sql stable security definer set search_path=public as $$
  select count(*) from public.volunteers;
$$;
grant execute on function public.get_public_volunteer_count() to anon, authenticated;

